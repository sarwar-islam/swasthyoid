"""Route reconciliation (B8a): the FastAPI routes from the app's own OpenAPI specification against the routes the web
mock answers (web/src/api/mock.ts). Writes docs/ROUTES.md; tests/test_route_reconciliation.py keeps it current.

    python -m swasthyoid.devtools.routes
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MOCK = ROOT / "web" / "src" / "api" / "mock.ts"
REPORT = ROOT / "docs" / "ROUTES.md"

# Why each mock route has no server route yet. Every one belongs to a later FRD phase (not B8), and in live mode the web
# shows the bilingual "not on the server yet" state for it (B8b), never a made-up answer.
UNBUILT = {
    ("GET", "/patients/{}/summary"): "M5 summary (FRD P3). Template summary with citations; needs the M5 backend.",
    ("GET", "/patients/{}/search"): "M5 search (FRD P3). Keyword search over the permitted events; needs the M5 backend.",
    ("POST", "/triage/sessions"): "M7 triage (FRD P8). Red-flag rules are REVIEWER-PENDING (FRD Q7).",
    ("POST", "/triage/sessions/{}/answer"): "M7 triage (FRD P8), next answer in a session; same as above.",
    ("GET", "/reminders"): "M8 reminders (FRD P8). Proposals from verified prescriptions; not built.",
    ("POST", "/reminders/{}/log"): "M8 adherence log (FRD P8); not built.",
    ("GET", "/vitals"): "M13 home vitals list (FRD P6); only per-patient thresholds exist (B6).",
    ("POST", "/vitals"): "M13 entering a reading (FRD P6); validation and escalation text are REVIEWER-PENDING.",
    ("POST", "/vitals/{}/correct"): "M13 correcting a reading (FRD P6); not built.",
}
# Server routes the web mock does not answer, and why that is fine.
SERVER_ONLY = {
    ("POST", "/auth/refresh"): "Token refresh. The web keeps its 15-minute access token in memory and signs in again "
                               "when it expires (a 401 shows 'sign in again'); it does not refresh yet.",
    ("GET", "/credentials/{}/document"): "An admin opens a credential's document. Uploading the document is unbuilt "
                                         "(B2 decision 6), so the console has no link to it yet.",
}


def _norm(path):
    return re.sub(r"\{[^}]+\}", "{}", path)


def server_routes():
    from swasthyoid.api.main import app
    return {(m.upper(), _norm(p.removeprefix("/api/v1"))) for p, ops in app.openapi()["paths"].items() for m in ops}


def mock_routes(src=None):
    src = MOCK.read_text(encoding="utf-8") if src is None else src
    routes = {(m, _norm(p)) for m, p in re.findall(r'\["(GET|POST|PUT|DELETE)", "(/[^"]*)"', src)}
    # routes made from a list: ...(["approve", "decline"] as const).map((verb) => ["POST", `/x/{id}/${verb}`, ...])
    for items, method, template in re.findall(r'\.\.\.\(\[([^\]]*)\] as const\)\.map\(\(\w+\)[^=]*=>\s*\["(\w+)", (`[^`]*`|\w+)', src):
        for value in re.findall(r'"([^"]*)"', items):
            path = re.sub(r"\$\{\w+\}", value, template.strip("`")) if template.startswith("`") else value
            routes.add((method, _norm(path)))
    return routes


def report(server=None, mock=None):
    server, mock = server or server_routes(), mock or mock_routes()
    both = server & mock
    lines = ["# Route reconciliation", "",
             "Generated by `python -m swasthyoid.devtools.routes` from the FastAPI OpenAPI specification and",
             "`web/src/api/mock.ts`; `tests/test_route_reconciliation.py` fails when this file is out of date. Paths are under",
             "`/api/v1` except `/health`; `{}` stands for a path parameter.", "",
             f"- FastAPI operations: **{len(server)}** ({len(server - {('GET', '/health')})} under `/api/v1`, plus `GET /health`)",
             f"- Web mock routes: **{len(mock)}**",
             f"- On both: **{len(both)}**",
             f"- Mock only (no server route yet): **{len(mock - server)}**",
             f"- Server only (no mock): **{len(server - mock)}**", "",
             "## Mock only: not on the server yet", "", "| Method | Path | Why |", "|---|---|---|"]
    lines += [f"| {m} | `{p}` | {UNBUILT.get((m, p), '**unexplained**')} |" for m, p in sorted(mock - server, key=lambda r: (r[1], r[0]))]
    lines += ["", "## Server only: no mock route", "", "| Method | Path | Why |", "|---|---|---|"]
    lines += [f"| {m} | `{p}` | {SERVER_ONLY.get((m, p), 'health check' if p == '/health' else '**unexplained**')} |"
              for m, p in sorted(server - mock, key=lambda r: (r[1], r[0]))]
    lines += ["", "## On both", "", "| Method | Path |", "|---|---|"]
    lines += [f"| {m} | `{p}` |" for m, p in sorted(both, key=lambda r: (r[1], r[0]))]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    REPORT.write_text(report(), encoding="utf-8", newline="\n")
    print(f"wrote {REPORT.relative_to(ROOT)}")
